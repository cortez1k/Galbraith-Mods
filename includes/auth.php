<?php
require_once __DIR__ . '/functions.php';

// Security: bind session to IP + User-Agent, 15-min timeout
function checkAdminSession() {
    if (empty($_SESSION['admin_id'])) return false;
    $maxAge = 900; // 15 minutes
    if (!empty($_SESSION['admin_last_active']) && (time() - $_SESSION['admin_last_active']) > $maxAge) {
        session_destroy();
        return false;
    }
    $ip = $_SERVER['REMOTE_ADDR'] ?? '';
    $ua = $_SERVER['HTTP_USER_AGENT'] ?? '';
    if (empty($_SESSION['admin_bind_ip']) || $_SESSION['admin_bind_ip'] !== $ip) {
        session_destroy();
        return false;
    }
    if (empty($_SESSION['admin_bind_ua']) || $_SESSION['admin_bind_ua'] !== $ua) {
        session_destroy();
        return false;
    }
    $_SESSION['admin_last_active'] = time();
    return true;
}

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $action = $_POST['action'] ?? '';

    if ($action === 'login') {
        $email = $_POST['email'] ?? '';
        $password = $_POST['password'] ?? '';
        $totpCode = $_POST['totp_code'] ?? '';
        $db = getDB();
        $stmt = $db->prepare('SELECT * FROM users WHERE email = ?');
        $stmt->execute([$email]);
        $user = $stmt->fetch();

        $userRoles = $user ? allRolesOf($user) : [];
        $isStaffLogin = $user && password_verify($password, $user['password'])
            && (bool)array_intersect(['admin', 'moderator', 'support'], $userRoles);
        if ($isStaffLogin) {
            // Moderators MUST have 2FA (secret is generated by admin when the role is assigned).
            // Admins and support agents have 2FA optional.
            $needsTotp = !empty($user['totp_secret']);
            $hasModeratorRole = in_array('moderator', $userRoles, true);
            if ($hasModeratorRole && empty($user['totp_secret'])) {
                $loginError = '2FA не настроен для этого модератора. Обратитесь к администратору.';
                goto loginEnd;
            }
            if ($needsTotp) {
                if (!verifyTOTPCode($user['totp_secret'], $totpCode)) {
                    $loginError = 'Неверный код двухфакторной аутентификации';
                    goto loginEnd;
                }
            }
            $_SESSION['admin_id'] = $user['id'];
            $_SESSION['admin_name'] = $user['name'];
            $_SESSION['admin_role'] = in_array('admin', $userRoles, true) ? 'admin'
                : (in_array('moderator', $userRoles, true) ? 'moderator' : 'support');
            $_SESSION['admin_last_active'] = time();
            $_SESSION['admin_bind_ip'] = $_SERVER['REMOTE_ADDR'] ?? '';
            $_SESSION['admin_bind_ua'] = $_SERVER['HTTP_USER_AGENT'] ?? '';
            $staffRedirects = ['moderator' => '/moderator', 'support' => '/support/chats'];
            redirect($staffRedirects[$_SESSION['admin_role']] ?? '/admin');
        } else {
            $loginError = 'Неверные учетные данные';
        }
        loginEnd:
    }

    if ($action === 'logout') {
        session_destroy();
        redirect('/');
    }
}
